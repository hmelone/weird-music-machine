"""Stage 8: validate the merged corpus and write research/05-validation-report.md.

Every number in the report is computed from the files, so it can be regenerated.
usage: python3 tools/validate_corpus.py
"""
import collections, hashlib, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
load = lambda p: json.loads((ROOT / p).read_text())
corpus = load('weird-music-machine-corpus.json')
baseline = load('research/baseline-250-fingerprints.json')
vocab = load('research/baseline-vocabulary.json')
pool = load('research/01-candidate-pool.json')
dedupe = load('research/02-dedupe-report.json')
selection = load('research/03-selection.json')
enriched = load('research/04-enriched-additions.json')
fp = lambda r: hashlib.sha256(json.dumps(r, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()

problems = []
original = corpus[:baseline['record_count']]
if [r['id'] for r in original] != baseline['ids_in_order']: problems.append('original IDs or order changed')
problems += [f"{r['id']} changed" for r in original if fp(r) != baseline['fingerprints'][r['id']]]
ids = [r['id'] for r in corpus]
if len(set(ids)) != len(ids): problems.append('duplicate IDs')
additions = enriched['records']
if corpus[len(original):] != additions: problems.append('corpus additions differ from research/04')
for i, r in enumerate(additions):
    if r['id'] != f'wmm-{121 + i:04d}': problems.append(f"{r['id']} out of sequence")
    if not all(isinstance(r[k], int) for k in ('weirdness', 'intensity', 'accessibility', 'year')): problems.append(f"{r['id']} unresolved field")
    if not r['curation_sources'] or not r['research_sources']: problems.append(f"{r['id']} missing sources")
    problems += [f"{r['id']} new trait {t}" for t in r['traits'] if t not in vocab['traits']]

area_of = {e['id']: e['area'] for e in enriched['evidence']}
by_area = collections.Counter(area_of[r['id']] for r in additions)
by_source = collections.Counter()
by_list_type = collections.Counter()
for r in additions:
    for c in r['curation_sources']:
        by_source[c['publication']] += 1
        kind = "Baker's Dozen (artist-curated)" if 'bakers-dozen' in c['url'] else 'Albums of the Year (ranked)' if 'albums-of-the-year' in c['url'] or 'best-albums' in c['url'] else 'Bandcamp Daily guide'
        by_list_type[kind] += 1
multi = [r for r in additions if len(r['curation_sources']) > 1]
dupes = [x for x in dedupe['results'] if x['status'] == 'rejected' and x.get('tier') in ('exact', 'edition', 'fuzzy', 'pool_duplicate')]
not_specific = [x for x in dedupe['results'] if x.get('reason') == 'not a specific release']
review = [r for r in additions if any('Manual review:' in n for n in r['research_notes'])]
new_styles = sorted({s for r in additions for s in r['styles'] if s not in vocab['styles']})
new_genres = sorted({g for r in additions for g in r['genres'] if g not in vocab['genres']})
new_traits = sorted({t for r in additions for t in r['traits'] if t not in vocab['traits']})
new_types = sorted({r['release_type'] for r in additions if r['release_type'] not in vocab['release_types']})
scores = {k: dict(sorted(collections.Counter(r[k] for r in additions).items())) for k in ('weirdness', 'intensity', 'accessibility')}

L = ['# Stage 8 — Validation report', '', '_Generated by `tools/validate_corpus.py`._', '',
     f"**Result: {'PASS' if not problems else 'FAIL'}**" + ('' if not problems else ' — ' + '; '.join(problems)), '',
     '| Measure | Value |', '| --- | --- |',
     f"| Original corpus size | {len(original)} |",
     f"| Curated source lists crawled | {pool['summary']['source_lists']} |",
     f"| Raw picks extracted | {pool['summary']['raw_picks']} |",
     f"| Candidates after merging repeat picks | {pool['summary']['candidates']} |",
     f"| Candidates naming a specific release | {pool['summary']['specific_releases']} |",
     f"| Duplicates of existing records rejected | {len(dupes)} |",
     f"| Non-specific picks rejected | {len(not_specific)} |",
     f"| Eligible after deduplication | {dedupe['summary']['eligible']} |",
     f"| Selected | {selection['summary']['selected']} |",
     f"| Rejected during research (unverifiable) | {len(enriched['rejected_in_research'])} |",
     f"| Records added | {len(additions)} ({additions[0]['id']} – {additions[-1]['id']}) |",
     f"| Final corpus size | {len(corpus)} |",
     f"| Additions cited by more than one list | {len(multi)} |",
     f"| Records flagged for manual review | {len(review)} |", '',
     '## Additions by musical area', '', '| Area | Records |', '| --- | --- |'] + [f'| {a} | {n} |' for a, n in by_area.most_common()] + [
     '', '## Additions by source', '', 'Counts are citations (a record cited by two lists counts twice).', '', '| Publication | Citations |', '| --- | --- |'] + [f'| {p} | {n} |' for p, n in by_source.most_common()] + [
     '', '| List type | Citations |', '| --- | --- |'] + [f'| {p} | {n} |' for p, n in by_list_type.most_common()] + [
     '', '## Duplicate candidates rejected', '', '| Candidate | Matches existing record | Tier |', '| --- | --- | --- |'] + [f"| {x['artist']} — {x['title']} | {x['corpus_match']['id']} {x['corpus_match']['title']} | {x['tier']} |" for x in dupes] + [
     '', '## Selections rejected during research', ''] + [f"- **{x['artist_in_source']} — {x['title_in_source']}**: {x['reason'].split(': ', 1)[-1]}" for x in enriched['rejected_in_research']] + [
     '', '## Records requiring manual review', '', '| ID | Record | Note |', '| --- | --- | --- |'] + [f"| {r['id']} | {r['artist']} — {r['title']} | {next(n for n in r['research_notes'] if 'Manual review:' in n).replace('Manual review: ', '')} |" for r in review] + [
     '', '## New vocabulary introduced', '',
     f"- **Traits:** {', '.join(new_traits) or 'none (all additions use the existing 27 traits)'}",
     f"- **Genres:** {', '.join(new_genres) or 'none (all additions use the existing genres)'}",
     f"- **Release types:** {', '.join(new_types) or 'none'}",
     f"- **Styles ({len(new_styles)}):** {', '.join(new_styles)}", '',
     '## Score distribution of the additions', ''] + [f"- **{k}:** " + ', '.join(f'{s}: {n}' for s, n in v.items()) for k, v in scores.items()]
(ROOT / 'research/05-validation-report.md').write_text('\n'.join(L) + '\n')
print('PASS' if not problems else 'FAIL: ' + '; '.join(problems))
